// Home map catalog: routers, mesh systems and internet provider gateways, with
// what the maker's own pages say about security support. Pure data,
// import-free; matching lives in lib/map.js (matchCatalog).
//
// Entry: { id, audience, brand, model, aliases, category, ispManaged,
//   supportStatus, supportEnds, autoUpdates, exploited, notes, sourceIds, status }
// - id: stored in saved maps (item.catalogId). Never rename one.
// - aliases: lowercase names people type or read off a label. Unique across
//   the whole catalog (the validator checks), so a match is never ambiguous.
// - category: "router" | "mesh" | "isp-gateway" (lib/content/map/categories.js).
// - supportStatus: "supported" | "ended" | "unknown".
// - supportEnds: the last date the maker commits to security updates
//   ("YYYY-MM-DD" | "YYYY-MM" | "YYYY"), or null when the maker publishes no
//   date. Support can run longer than a commitment; an "ended" entry with no
//   published date says so in notes.
// - autoUpdates: "default-on" | "optional" | "manual" | "unknown", and only
//   what a cited page says.
// - exploited: true when a flaw in the model is on CISA's Known Exploited
//   Vulnerabilities catalog (cisa-kev-catalog). It says the model has had a
//   flaw used in real attacks, not that a given router is affected today.
// - status: "published" only when sourceIds include a page we read;
//   anything we could not confirm is "unknown" and "draft".
//
// Every date was read on 2026-10-29 from the cited page. A person must check
// each date against the cited page before relying on it, at launch and at
// every review: makers change these lists without notice. We never claim to
// know anything about a member's actual device, only what the catalog says
// about the model.

